"""Profile the raw Olist CSV files and write a data-quality report."""

from __future__ import annotations

import logging
from pathlib import Path

import pandas as pd

LOGGER = logging.getLogger(__name__)
PROJECT_ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = PROJECT_ROOT / "data" / "raw"
DOCS_DIR = PROJECT_ROOT / "docs"
REPORT_PATH = DOCS_DIR / "data_quality_report.md"

RAW_FILES = {
    "orders": "olist_orders_dataset.csv",
    "order_items": "olist_order_items_dataset.csv",
    "payments": "olist_order_payments_dataset.csv",
    "reviews": "olist_order_reviews_dataset.csv",
    "customers": "olist_customers_dataset.csv",
    "products": "olist_products_dataset.csv",
    "sellers": "olist_sellers_dataset.csv",
    "geolocation": "olist_geolocation_dataset.csv",
    "category_translation": "product_category_name_translation.csv",
}

DATE_COLUMNS = {
    "orders": [
        "order_purchase_timestamp",
        "order_approved_at",
        "order_delivered_carrier_date",
        "order_delivered_customer_date",
        "order_estimated_delivery_date",
    ],
    "order_items": ["shipping_limit_date"],
    "reviews": ["review_creation_date", "review_answer_timestamp"],
}

KEY_COLUMNS = {
    "orders": [("order_id",)],
    "order_items": [("order_id", "order_item_id")],
    "payments": [("order_id", "payment_sequential")],
    "reviews": [("review_id",), ("order_id",)],
    "customers": [("customer_id",)],
    "products": [("product_id",)],
    "sellers": [("seller_id",)],
    "geolocation": [("geolocation_zip_code_prefix",)],
    "category_translation": [("product_category_name",)],
}


def load_tables() -> dict[str, pd.DataFrame]:
    """Load all expected raw tables and parse their date columns."""
    tables: dict[str, pd.DataFrame] = {}
    for name, filename in RAW_FILES.items():
        path = RAW_DIR / filename
        if not path.exists():
            raise FileNotFoundError(f"Missing raw input: {path}")
        LOGGER.info("Loading %s", path.name)
        table = pd.read_csv(path)
        for column in DATE_COLUMNS.get(name, []):
            if column in table.columns:
                table[column] = pd.to_datetime(table[column], errors="coerce")
        tables[name] = table
    return tables


def null_summary(table: pd.DataFrame) -> list[tuple[str, int, float]]:
    nulls = table.isna().sum()
    return [
        (column, int(count), round(float(count / len(table) * 100), 2))
        for column, count in nulls.items()
        if count
    ]


def exact_duplicate_rows(table: pd.DataFrame) -> int:
    return int(table.duplicated().sum())


def key_duplicate_summary(
    table_name: str, table: pd.DataFrame
) -> list[tuple[str, int, int]]:
    """Return key label, duplicate groups, and rows in duplicate groups."""
    summaries = []
    for columns in KEY_COLUMNS.get(table_name, []):
        key_label = ", ".join(columns)
        duplicate_mask = table.duplicated(subset=list(columns), keep=False)
        duplicate_groups = int(table.loc[duplicate_mask, list(columns)].drop_duplicates().shape[0])
        duplicate_rows = int(duplicate_mask.sum())
        if duplicate_groups:
            summaries.append((key_label, duplicate_groups, duplicate_rows))
    return summaries


def date_ranges(table_name: str, table: pd.DataFrame) -> list[tuple[str, str, str]]:
    ranges = []
    for column in DATE_COLUMNS.get(table_name, []):
        if column not in table:
            continue
        values = table[column].dropna()
        if not values.empty:
            ranges.append((column, values.min().date().isoformat(), values.max().date().isoformat()))
    return ranges


def orphan_count(child: pd.Series, parent: pd.Series) -> int:
    return int((~child.dropna().isin(parent.dropna())).sum())


def build_report(tables: dict[str, pd.DataFrame]) -> str:
    lines = [
        "# Olist data quality report",
        "",
        "Generated by `python run_pipeline.py profile` from the files in `data/raw`.",
        "",
        "## Table profiles",
        "",
        "| Table | Rows | Columns | Exact duplicate rows |",
        "|---|---:|---:|---:|",
    ]
    for name, table in tables.items():
        lines.append(f"| `{name}` | {len(table):,} | {len(table.columns)} | {exact_duplicate_rows(table):,} |")

    lines.extend(["", "## Null values", ""])
    for name, table in tables.items():
        nulls = null_summary(table)
        lines.extend([f"### `{name}`", ""])
        if not nulls:
            lines.append("No null values detected.")
        else:
            lines.extend(
                ["| Column | Null rows | Null percentage |", "|---|---:|---:|"]
                + [f"| `{column}` | {count:,} | {percentage:.2f}% |" for column, count, percentage in nulls]
            )
        lines.append("")

    lines.extend(
        [
            "## Actionable duplicate keys",
            "",
            "This section checks only documented primary or business keys. Repeated "
            "attributes such as status, category, price, or state are not treated as "
            "duplicate records.",
            "",
            "| Table | Key | Duplicate key groups | Rows in duplicate groups | Excess rows beyond first |",
            "|---|---|---:|---:|---:|",
        ]
    )
    for name, table in tables.items():
        summaries = key_duplicate_summary(name, table)
        for key, groups, rows in summaries:
            lines.append(f"| `{name}` | `{key}` | {groups:,} | {rows:,} | {rows - groups:,} |")
    if not any(key_duplicate_summary(name, table) for name, table in tables.items()):
        lines.append("| All tables | Documented keys | 0 | 0 | 0 |")

    lines.extend(["## Date ranges", "", "| Table | Column | Minimum | Maximum |", "|---|---|---|---|"])
    for name, table in tables.items():
        for column, minimum, maximum in date_ranges(name, table):
            lines.append(f"| `{name}` | `{column}` | {minimum} | {maximum} |")

    lines.extend(["", "## Referential integrity", "", "| Child table | Key | Parent table | Orphans |", "|---|---|---|---:|"])
    relationships = [
        ("orders", "customer_id", "customers", "customer_id"),
        ("order_items", "order_id", "orders", "order_id"),
        ("order_items", "product_id", "products", "product_id"),
        ("order_items", "seller_id", "sellers", "seller_id"),
        ("payments", "order_id", "orders", "order_id"),
        ("reviews", "order_id", "orders", "order_id"),
    ]
    for child_table, child_key, parent_table, parent_key in relationships:
        count = orphan_count(tables[child_table][child_key], tables[parent_table][parent_key])
        lines.append(f"| `{child_table}` | `{child_key}` | `{parent_table}` | {count:,} |")

    orders = tables["orders"]
    delivered = orders["order_status"].eq("delivered")
    non_delivered = ~delivered
    delivered_without_date = int((delivered & orders["order_delivered_customer_date"].isna()).sum())
    non_delivered_with_date = int((non_delivered & orders["order_delivered_customer_date"].notna()).sum())
    delivered_before_purchase = int(
        (
            delivered
            & orders["order_delivered_customer_date"].notna()
            & (orders["order_delivered_customer_date"] < orders["order_purchase_timestamp"])
        ).sum()
    )
    products = tables["products"]
    translations = tables["category_translation"]["product_category_name"]
    missing_translations = sorted(
        set(products["product_category_name"].dropna()) - set(translations.dropna())
    )
    payments = tables["payments"]

    lines.extend(
        [
            "",
            "## Business-rule checks",
            "",
            f"- Order statuses: {orders['order_status'].value_counts().to_dict()}",
            f"- Delivered orders missing customer delivery date: **{delivered_without_date:,}**",
            f"- Non-delivered orders with customer delivery date: **{non_delivered_with_date:,}**",
            f"- Delivered orders delivered before purchase: **{delivered_before_purchase:,}**",
            f"- Order items with negative price: **{int((tables['order_items']['price'] < 0).sum()):,}**",
            f"- Order items with negative freight: **{int((tables['order_items']['freight_value'] < 0).sum()):,}**",
            f"- Payments with zero value: **{int((payments['payment_value'] == 0).sum()):,}**",
            f"- Payments with `not_defined` type: **{int(payments['payment_type'].eq('not_defined').sum()):,}**",
            f"- Product categories missing from translation file: **{len(missing_translations)}**"
            + (f" (`{', '.join(missing_translations)}`)" if missing_translations else ""),
            "",
            "## Cleaning rules",
            "",
            "The rules applied in Phase 2 are documented in `CLAUDE.md`.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    tables = load_tables()
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(build_report(tables), encoding="utf-8")
    LOGGER.info("Wrote %s", REPORT_PATH)


if __name__ == "__main__":
    main()
